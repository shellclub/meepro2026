-- Creates the categories used in the BigSeller file (ไม่มีหมวดหมู่ / Vat 7% / Nestle Brand / Buzz Netura)
-- if missing, then assigns each product its category from the file. Products without any category
-- are placed in "ไม่มีหมวดหมู่". Existing categories and categories already set by an admin are left alone.
INSERT INTO categories (name, slug, sortOrder, isActive, createdAt, updatedAt)
SELECT 'ไม่มีหมวดหมู่', 'no-category', COALESCE((SELECT MAX(sortOrder) FROM categories c2), 0) + 1, 1, NOW(), NOW()
WHERE NOT EXISTS (SELECT 1 FROM categories WHERE name = 'ไม่มีหมวดหมู่');
INSERT INTO categories (name, slug, sortOrder, isActive, createdAt, updatedAt)
