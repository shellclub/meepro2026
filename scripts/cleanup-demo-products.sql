       (SELECT COUNT(*) FROM order_items oi WHERE oi.productId = p.id) AS orderLines
FROM products p
WHERE p.sku IS NULL OR p.sku NOT IN (SELECT sku FROM keep_skus)
ORDER BY p.id;
SELECT COUNT(*) AS will_delete FROM products WHERE sku IS NULL OR sku NOT IN (SELECT sku FROM keep_skus);
SELECT COUNT(*) AS will_keep   FROM products WHERE sku IN (SELECT sku FROM keep_skus);

