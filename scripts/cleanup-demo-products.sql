WHERE NOT EXISTS (SELECT 1 FROM categories WHERE name = 'Vat 7%') AND NOT EXISTS (SELECT 1 FROM categories WHERE slug = 'vat-7');
INSERT INTO categories (name, slug, sortOrder, isActive, createdAt, updatedAt)
