UPDATE products p
JOIN keep_skus k ON k.sku = p.sku
JOIN categories c ON c.name = k.category
SET p.categoryId = c.id
WHERE p.categoryId IS NULL;

UPDATE products p
JOIN categories c ON c.name = 'ไม่มีหมวดหมู่'
SET p.categoryId = c.id
WHERE p.categoryId IS NULL;

SELECT c.id, c.name, c.slug, COUNT(p.id) AS products
FROM categories c LEFT JOIN products p ON p.categoryId = c.id
GROUP BY c.id ORDER BY c.sortOrder;
